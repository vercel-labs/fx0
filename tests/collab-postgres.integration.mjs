// Opt in ONLY to a disposable local Unix-socket Postgres cluster; never loads .env
// or uses DATABASE_URL/PGHOST/PGPASSWORD. No npm driver or network is needed.
// FX0_COLLAB_TEST_SOCKET=/tmp/<cluster>/socket [FX0_COLLAB_TEST_PORT=55432] \
//   node --experimental-strip-types --test tests/collab-postgres.integration.mjs
// The caller owns starting/stopping Postgres. Each case owns only a random schema.
// Capture production batches rather than reimplementing SQL. This proves their
// READ COMMITTED scheduling/effects, not Neon HTTP transport or JS error mapping.
const socket = process.env.FX0_COLLAB_TEST_SOCKET
const port = process.env.FX0_COLLAB_TEST_PORT ?? '55432'
const token = (letter) => letter.repeat(43)
const roomA = 'A'.repeat(22), roomB = 'B'.repeat(22)
const hourlyUses = [{ key: 'shared-address', limit: 1 }]
const schemaSQL = readFileSync(new URL('../migrations/006_ampersand_rooms.sql', import.meta.url), 'utf8')

// Deliberately limited to values generated by this fixture, never user input.
function literal(value) {
  if (value === null) return 'NULL'
  if (typeof value === 'number' && Number.isFinite(value)) return String(value)
  if (typeof value === 'boolean') return String(value)
  assert.equal(typeof value, 'string')
  assert.doesNotMatch(value, /[\\\r\n\0]/)
  return `'${value.replaceAll("'", "''")}'`
}
const bind = ({ text, values = [] }) => text.replace(/\$(\d+)\b/g, (_, n) => {
  assert.ok(Number(n) <= values.length)
  return literal(values[Number(n) - 1])
})

// Native psql CSV, including quoted JSON cells and embedded commas/newlines.
function csv(text) {
  const rows = [], row = []
  let value = '', quoted = false
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]
    if (ch === '"') {
      if (quoted && text[i + 1] === '"') { value += '"'; i++ }
      else quoted = !quoted
    } else if (!quoted && (ch === ',' || ch === '\n')) {
      row.push(value); value = ''
      if (ch === '\n') { rows.push([...row]); row.length = 0 }
    } else value += ch
  }
  assert.equal(quoted, false, 'complete CSV output')
  if (value || row.length) rows.push([...row, value])
  const [columns, ...data] = rows
  return data.map((cells) => Object.fromEntries(columns.map((key, i) => [key, cells[i]])))
}

async function capture(operation) {
  const stop = new Error('captured production batch')
  let batch
  const query = async () => { throw new Error('unexpected standalone query before batch') }
  query.transaction = async (statements) => { batch = statements; throw stop }
  await assert.rejects(operation(createRoomStore(query)), (error) => error === stop)
  assert.ok(batch?.length >= 2)
  assert.match(batch[0].text, /FOR UPDATE/)
  return batch
}

function startSQL(schema, sql) {
  const name = `fx0-collab-${randomBytes(8).toString('hex')}`
  const child = spawn('psql', [
    '-X', '--csv', '-q', '-v', 'ON_ERROR_STOP=1', '-h', socket,
    '-p', port, '-U', userInfo().username, '-d', 'postgres',
  ], {
    // Do not inherit any ambient database credentials, service files or options.
    env: { PATH: process.env.PATH ?? '/usr/bin:/bin', LC_ALL: 'C', PGAPPNAME: name },
    stdio: ['pipe', 'pipe', 'pipe'],
  })
  let stdout = '', stderr = ''
  child.stdout.setEncoding('utf8').on('data', (chunk) => { stdout += chunk })
  child.stderr.setEncoding('utf8').on('data', (chunk) => { stderr += chunk })
  const done = new Promise((resolve, reject) => {
    child.on('error', reject)
    child.on('close', (code) => code === 0 ? resolve(stdout) : reject(new Error(`psql exit ${code}: ${stderr}`)))
    child.stdin.on('error', reject)
  })
  // Register immediately, including while the harness is observing lock waits.
  done.catch(() => {})
  child.stdin.end(`SET search_path TO ${schema}; SET statement_timeout = '15s'; SET lock_timeout = '10s';\n${sql}\n`)
  return { name, done }
}

async function fixture(t) {
  const schema = `collab_pg_${randomBytes(8).toString('hex')}`
  const exec = (sql) => startSQL(schema, sql).done
  await exec(`CREATE SCHEMA ${schema}; SET search_path TO ${schema}; ${schemaSQL}`)
  t.after(() => exec(`DROP SCHEMA ${schema} CASCADE;`))
  const rows = async (sql) => csv(await exec(sql))
  const seed = async (ids = [roomA]) => {
    for (const id of ids) await exec(`
      INSERT INTO ampersand_rooms (id, title) VALUES (${literal(id)}, 'Board');
      INSERT INTO ampersand_members (id, room_id, name, token_hash, joined_at)
        VALUES (${literal(`member-${id}`)}, ${literal(id)}, 'Alice', ${literal(hashHandle(token('a')))}, 1);
      INSERT INTO ampersand_invites (room_id, invite_hash) VALUES (${literal(id)}, ${literal(hashHandle(token('i')))});
    `)
  }
  const state = async () => {
    const [row] = await rows(`SELECT
      (SELECT COUNT(*) FROM ampersand_messages) AS messages,
      (SELECT COALESCE(SUM(units), 0) FROM ampersand_usage) AS daily,
      (SELECT COALESCE(SUM(count), 0) FROM ampersand_hourly) AS hourly;`)
    return Object.fromEntries(Object.entries(row).map(([k, v]) => [k, Number(v)]))
  }
  const batchSQL = (batch) => batch.map((statement, i) =>
    `${i === batch.length - 1 ? '\\echo FX0_RESULT_BEGIN\n' : ''}${bind(statement)};\n`).join('') + '\\echo FX0_RESULT_END\n'
  const result = (output) => csv(output.split('FX0_RESULT_BEGIN\n')[1].split('FX0_RESULT_END\n')[0])
  const execute = async (batch) => result(await exec(`BEGIN ISOLATION LEVEL READ COMMITTED;\n${batchSQL(batch)}COMMIT;`))
  const waitFor = async (sql, predicate, label) => {
    const until = Date.now() + 5000
    do {
      const found = await rows(sql)
      if (predicate(found)) return found
      await new Promise((resolve) => setTimeout(resolve, 20))
    } while (Date.now() < until)
    assert.fail(`did not observe ${label}`)
  }
  // A runs its real batch, then sleeps *inside the same transaction* holding its
  // locks/uncommitted effects. B starts only after A is seen in PgSleep. A third
  // connection proves B is blocked by A, not just launched at roughly the same time.
  const overlap = async (first, second) => {
    const a = startSQL(schema, `BEGIN ISOLATION LEVEL READ COMMITTED;\n${batchSQL(first)}SELECT pg_sleep(2); COMMIT;`)
    let b
    try {
      const [holder] = await waitFor(`SELECT pid, wait_event FROM pg_stat_activity WHERE application_name = ${literal(a.name)};`,
        (rows) => rows[0]?.wait_event === 'PgSleep', 'holder sleeping with uncommitted effects')
      b = startSQL(schema, `BEGIN ISOLATION LEVEL READ COMMITTED;\n${batchSQL(second)}COMMIT;`)
      const [waiter] = await waitFor(`SELECT pid, wait_event_type, ${Number(holder.pid)} = ANY(pg_blocking_pids(pid)) AS blocked_by_holder
        FROM pg_stat_activity WHERE application_name = ${literal(b.name)};`,
      (rows) => rows[0]?.wait_event_type === 'Lock' && rows[0]?.blocked_by_holder === 't', 'independent waiter blocked by holder')
      assert.notEqual(waiter.pid, holder.pid)
      t.diagnostic(`READ COMMITTED: backend ${waiter.pid} waited on backend ${holder.pid}; holder slept in transaction`)
      return [result(await a.done), result(await b.done)]
    } finally {
      await Promise.allSettled([a.done, ...(b ? [b.done] : [])])
    }
  }
  return { exec, rows, seed, state, execute, overlap }
}

const message = (id, requestId, extra = {}) => capture((store) => store.appendMessage(id, token('a'), {
  text: 'Build this', requestId, dailyLimit: 20, ...extra,
}))
const claim = (id, runner) => capture((store) => store.claimRun(id, runner, 0, 60_000, 1))
const roomLock = (id) => ({ text: 'SELECT id FROM ampersand_rooms WHERE id = $1 FOR UPDATE', values: [id] })

test('collab production batches on independent local PostgreSQL connections', {
  skip: !socket && 'set FX0_COLLAB_TEST_SOCKET to an isolated disposable cluster Unix socket directory',
  timeout: 120_000,
}, async (t) => {
  assert.ok(isAbsolute(socket), 'Unix socket directory must be absolute; TCP/URLs are not accepted')
  assert.match(port, /^\d{1,5}$/)

  await t.test('duplicate messages at daily/hourly quota=1 are accepted once, including after lock wait', async (t) => {
    const db = await fixture(t)
    await db.seed()
    const batch = await message(roomA, 'same', { dailyLimit: 1, hourlyUses })
    assert.equal(batch.length, 3)
    const [first, second] = await db.overlap(batch, batch)
    assert.equal(first[0].duplicate, 'f')
    assert.equal(second[0].duplicate, 't')
    assert.equal(second[0].refusal, '', 'dedup must precede exhausted quota checks')
    assert.equal(JSON.parse(first[0].result).length, 1)
    assert.deepEqual(JSON.parse(second[0].result), [])
    assert.deepEqual(await db.state(), { messages: 1, daily: 1, hourly: 1 })
  })

  await t.test('hourly quota across rooms has one winner and no partial loser reservations', async (t) => {
    const db = await fixture(t)
    await db.seed([roomA, roomB])
    const batches = await Promise.all([roomA, roomB].map((id, i) => message(id, `request-${i}`, {
      hourlyUses: [...hourlyUses, { key: `browser-${i}`, limit: 10 }],
    })))
    const [first, second] = await db.overlap(...batches)
    assert.equal(first[0].refusal, '')
    assert.equal(second[0].refusal, 'hourly')
    assert.deepEqual(JSON.parse(second[0].result), [])
    assert.deepEqual(await db.state(), { messages: 1, daily: 1, hourly: 2 })
    assert.deepEqual(await db.rows('SELECT key, count FROM ampersand_hourly ORDER BY key;'), [
      { key: 'browser-0', count: '1' }, { key: 'shared-address', count: '1' },
    ])
  })

  await t.test('maxMembers=2 racing joins admit exactly one new member', async (t) => {
    const db = await fixture(t)
    await db.seed()
    const batches = await Promise.all(['b', 'c'].map((letter) => capture((store) => store.joinRoom({
      id: roomA, invite: token('i'), name: letter, token: token(letter), maxMembers: 2,
      hourlyUses: [{ key: `join-${letter}`, limit: 1 }],
    }))))
    const [first, second] = await db.overlap(...batches)
    assert.equal(first[0].refusal, '')
    assert.equal(second[0].refusal, 'full')
    assert.deepEqual(JSON.parse(second[0].result), [])
    assert.deepEqual(await db.rows('SELECT COUNT(*) AS n FROM ampersand_members;'), [{ n: '2' }])
    assert.deepEqual(await db.state(), { messages: 0, daily: 0, hourly: 1 })
    const [repeat] = await db.execute(batches[0])
    assert.equal(repeat.duplicate, 't')
    assert.equal(repeat.refusal, '')
    assert.deepEqual(await db.state(), { messages: 0, daily: 0, hourly: 1 })
  })

  await t.test('maxRunningRooms=1 is enforced across rooms after coordination lock wait', async (t) => {
    const db = await fixture(t)
    await db.seed([roomA, roomB])
    const batches = await Promise.all([claim(roomA, 'runner-a'), claim(roomB, 'runner-b')])
    const [first, second] = await db.overlap(...batches)
    assert.equal(first.length, 1)
    assert.equal(second.length, 0)
    assert.deepEqual(await db.rows('SELECT COUNT(*) AS n FROM ampersand_rooms WHERE runner_until > EXTRACT(EPOCH FROM clock_timestamp()) * 1000;'), [{ n: '1' }])
    await db.exec(`UPDATE ampersand_rooms SET runner = NULL, runner_until = NULL WHERE id = ${literal(roomA)};`)
    assert.equal((await db.execute(batches[1])).length, 1, 'loser can claim after capacity is released')
  })

  await t.test('lease takeover while waiting rejects every stale trusted write without effects', async (t) => {
    const db = await fixture(t)
    await db.seed()
    await db.execute(await claim(roomA, 'old-runner'))
    const takeover = [roomLock(roomA), {
      text: 'UPDATE ampersand_rooms SET runner = $2, runner_until = EXTRACT(EPOCH FROM clock_timestamp()) * 1000 + 60000 WHERE id = $1 RETURNING id',
      values: [roomA, 'new-runner'],
    }]
    const stale = { runner: 'old-runner' }
    const effects = [
      (s) => s.assertRun(roomA, stale),
      (s) => s.appendAssistant(roomA, 'must not persist', stale),
      (s) => s.publishDesign(roomA, '<p>must not persist</p>', stale),
      (s) => s.recordActivity(roomA, { agent: 'Builder', kind: 'message', text: 'must not persist' }, stale),
      (s) => s.saveAgentSession(roomA, 'Builder', { sessionId: 'must not persist', deliveredThrough: 9 }, stale),
      (s) => s.setStatus(roomA, 'error', 'must not persist', stale, true),
      (s) => s.markProcessed(roomA, 9, stale),
    ]
    const batches = await Promise.all(effects.map(capture))
    const [, waited] = await db.overlap(takeover, batches[1])
    assert.equal(waited[0].owner_ok, 'f', 'ownership check must see takeover committed after lock wait')
    for (const batch of batches) {
      const [row] = await db.execute(batch)
      assert.equal(row.owner_ok, 'f')
      assert.deepEqual(JSON.parse(row.result), [])
    }
    const [snapshot] = await db.rows(`SELECT row_to_json(r) AS room FROM ampersand_rooms r;`)
    const room = JSON.parse(snapshot.room)
    assert.equal(room.runner, 'new-runner')
    assert.equal(room.processed_through, 0)
    assert.equal(room.status, 'idle')
    assert.equal(room.version, 1)
    assert.equal(room.cleanup_blocked, false)
    for (const table of ['ampersand_messages', 'ampersand_revisions', 'ampersand_activity', 'ampersand_sessions']) {
      assert.deepEqual(await db.rows(`SELECT COUNT(*) AS n FROM ${table};`), [{ n: '0' }])
    }
    await db.exec('UPDATE ampersand_rooms SET runner_until = 1;')
    const [expired] = await db.execute(await capture((s) => s.appendAssistant(roomA, 'must not persist', { runner: 'new-runner' })))
    assert.equal(expired.owner_ok, 'f', 'same owner with expired lease is fenced too')
    assert.deepEqual(JSON.parse(expired.result), [])
  })

  await t.test('input watermark is checked under the write lock after a concurrent message commits', async (t) => {
    const db = await fixture(t)
    await db.seed()
    await db.execute(await message(roomA, 'first'))
    const [{ newest }] = await db.rows('SELECT MAX(id) AS newest FROM ampersand_messages;')
    await db.execute(await claim(roomA, 'runner'))
    const guard = { runner: 'runner', throughId: Number(newest) }
    const publish = await capture((s) => s.publishDesign(roomA, '<p>stale</p>', guard))
    const [current] = await db.execute(await capture((s) => s.assertRun(roomA, guard)))
    assert.equal(current.owner_ok, 't')
    assert.equal(current.inputs_ok, 't')
    const [, waited] = await db.overlap(await message(roomA, 'second'), publish)
    assert.equal(waited[0].owner_ok, 't')
    assert.equal(waited[0].inputs_ok, 'f', 'watermark must use a fresh snapshot after waiting')
    assert.deepEqual(JSON.parse(waited[0].result), [])
    for (const effect of [
      (s) => s.assertRun(roomA, guard),
      (s) => s.appendAssistant(roomA, 'stale', guard),
      (s) => s.markProcessed(roomA, Number(newest), guard),
      (s) => s.publishDesign(roomA, '<p>stale</p>', guard),
      (s) => s.recordActivity(roomA, { agent: 'Builder', kind: 'message', text: 'stale' }, guard),
    ]) {
      const [row] = await db.execute(await capture(effect))
      assert.equal(row.owner_ok, 't')
      assert.equal(row.inputs_ok, 'f')
      assert.deepEqual(JSON.parse(row.result), [])
    }
    assert.deepEqual(await db.state(), { messages: 2, daily: 2, hourly: 0 })
    assert.deepEqual(await db.rows('SELECT processed_through, status, version FROM ampersand_rooms;'), [
      { processed_through: '0', status: 'idle', version: '3' },
    ])
    for (const table of ['ampersand_revisions', 'ampersand_activity']) {
      assert.deepEqual(await db.rows(`SELECT COUNT(*) AS n FROM ${table};`), [{ n: '0' }])
    }
    // Sessions intentionally fence ownership only, preserving superseded session IDs.
    const [session] = await db.execute(await capture((s) => s.saveAgentSession(roomA, 'Builder', {
      sessionId: 'retained-session', deliveredThrough: Number(newest),
    }, guard)))
    assert.equal(session.owner_ok, 't')
    assert.equal(session.inputs_ok, 't')
    assert.equal(JSON.parse(session.result).length, 1)
    // Failure records the attempted batch, not the newer input. It must still
    // verify ownership, but cannot discard the error merely because input changed.
    const [failed] = await db.execute(await capture((s) => s.setStatus(roomA, 'error', 'first batch failed', guard, false, Number(newest))))
    assert.equal(failed.owner_ok, 't')
    assert.equal(failed.inputs_ok, 't')
    assert.equal(JSON.parse(failed.result).length, 1)
    assert.deepEqual(await db.rows('SELECT status, failed_through FROM ampersand_rooms;'), [{ status: 'error', failed_through: newest }])
    await db.exec('UPDATE ampersand_rooms SET runner = NULL, runner_until = NULL;')
    const claimed = await db.execute(await claim(roomA, 'next-batch'))
    assert.equal(claimed.length, 1, 'the already admitted newer input may start after the failed batch')
  })
})
